  await page.getByRole('button', { name: '全部', exact: true }).click()
  let release!: () => void
  const blocker = new Promise<void>(resolve => { release = resolve })
  await page.route('**/api/questions', async route => { await blocker; await route.fulfill({status:503,contentType:'application/json',body:JSON.stringify({code:'TEST_UNAVAILABLE',message:'Simulated backend unavailable'})}) })
  await page.locator('#question').fill('backend port')
  await page.getByRole('button', { name: '尋找證據' }).click()
