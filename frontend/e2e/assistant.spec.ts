import { test, expect } from '@playwright/test'
import path from 'node:path'
import { mkdirSync } from 'node:fs'
const screenshots = path.resolve(process.cwd(), process.env.AKA_SCREENSHOTS ?? '../work/screenshots')
mkdirSync(screenshots, { recursive: true })

test('real baseline answer, canonical source verification and no-evidence state', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', e => errors.push(e.message))
  await page.goto('/')
  await expect(page.getByText('離線檢索 / 原文摘錄', { exact: true })).toBeVisible()
  const status = await (await page.request.get('/api/status')).json()
  expect(status.configuration).toMatchObject({ chunkMaxChars: 800, topK: 5, coverageThreshold: 0.6, bm25K1: 1.2, bm25B: 0.75 })
  const responsePromise = page.waitForResponse(response => response.url().endsWith('/api/questions') && response.request().method() === 'POST')
  await expect(page.getByText('從一個問題開始', { exact: true })).toBeVisible()
  await page.screenshot({ path: path.join(screenshots, '01-workspace.png'), fullPage: true })
  await page.getByRole('button', { name: /架構與技術/ }).click()
  const answer = await (await responsePromise).json()
  expect(answer.configuration).toEqual(status.configuration)
  await expect(page.getByText('找到原文摘錄', { exact: true })).toBeVisible()
  await expect(page.locator('blockquote')).toContainText(['18081'])
  await expect(page.locator('blockquote').filter({ hasText: '4175' })).toHaveCount(2)
  await page.getByRole('button', { name: '核對目前來源版本' }).click()
  await expect(page.getByText('已核對：目前文件版本與引用原文一致。', { exact: true })).toBeVisible()
  await page.screenshot({ path: path.join(screenshots, '02-answer-sources.png'), fullPage: true })
  await page.getByLabel('向文件提問', { exact: false }).fill('What is the employee salary and vacation budget?')
  await page.getByRole('button', { name: '尋找證據' }).click()
  await expect(page.getByText('證據不足', { exact: true })).toBeVisible()
  await expect(page.locator('blockquote')).toHaveCount(0)
  await page.screenshot({ path: path.join(screenshots, '03-insufficient-evidence.png'), fullPage: true })
  expect(errors).toEqual([])
})

test('import update delete through Vue and backend; old text disappears', async ({ page, request }) => {
  const id = 'browser-lifecycle'
  // Clean only this test document when re-running after an interrupted test.
  const existing = await request.get(`/api/documents/${id}`)
  if (existing.ok()) await request.delete(`/api/documents/${id}?expectedVersion=${(await existing.json()).version}`)
  await page.goto('/')
  await page.getByRole('button', { name: /文件資料庫/ }).click()
  await page.getByRole('button', { name: '＋ 匯入文件' }).click()
  await page.getByLabel('文件 ID', { exact: true }).fill(id)
  await page.getByLabel('文件標題', { exact: true }).fill('Browser lifecycle fixture')
  await page.getByLabel('Markdown 內容', { exact: true }).fill('## Version\nuilifecycleoldtoken unique evidence.')
  await page.getByRole('button', { name: '匯入並建立索引' }).click()
  const card = page.locator('.document-card').filter({ hasText: 'Browser lifecycle fixture' })
  await expect(card).toBeVisible()
  const before = await (await request.get(`/api/documents/${id}`)).json()
  await card.getByRole('button', { name: '檢視 / 更新' }).click()
  await page.getByLabel('Markdown 內容', { exact: true }).fill('## Version\nuilifecyclenewtoken updated evidence.')
  await page.getByRole('button', { name: '儲存新版本' }).click()
  await expect(card).toContainText(`v${before.version + 1}`)
  const oldQuery = await request.post('/api/questions', { data: { question: 'uilifecycleoldtoken', documentIds: [id] } })
  expect((await oldQuery.json()).sources).toHaveLength(0)
  const currentQuery = await request.post('/api/questions', { data: { question: 'uilifecyclenewtoken', documentIds: [id] } })
  expect((await currentQuery.json()).status).toBe('EXTRACTS_FOUND')
  const oldCitation = await request.get(`/api/documents/${id}/chunks/${before.chunks[0].id}?version=${before.version}`)
  expect(oldCitation.status()).toBe(409)
  await card.getByRole('button', { name: '刪除', exact: true }).click()
  await card.getByRole('button', { name: '確認刪除', exact: true }).click()
  await expect(card).toHaveCount(0)
  expect((await request.get(`/api/documents/${id}`)).status()).toBe(404)
  await page.screenshot({ path: path.join(screenshots, '04-document-library.png'), fullPage: true })
})

